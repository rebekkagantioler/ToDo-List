// Ein fortlaufender 365-Tage-Zyklus vermeidet Wiederholungen auch in Schaltjahren.
export function dailySaying(date=new Date()){
 const parts=new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/Vienna',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(date);
 const part=(name:string)=>Number(parts.find(p=>p.type===name)!.value);
 const day=Math.floor((Date.UTC(part('year'),part('month')-1,part('day'))-Date.UTC(2026,0,1))/86400000);
 const index=((day%dailySayings.length)+dailySayings.length)%dailySayings.length;
 return {text:dailySayings[index],index};
}
